import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { z } from 'zod';
import { tools } from '../dist/tools.js';

// Match the conversion used by tools/list. Importing the registry does not
// construct a client, load credentials, or make network requests.
const schemaOf = schema => z.toJSONSchema(schema, { target: 'draft-7', io: 'input' });
const cell = value => String(value).replaceAll('|', '&#124;').replaceAll('\n', ' ').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
function typeOf(schema) {
  if (schema.anyOf) return schema.anyOf.map(typeOf).join(' or ');
  if (schema.enum) return schema.enum.map(value => JSON.stringify(value)).join(', ');
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  if (schema.type === 'array') return `array of ${typeOf(schema.items || {})}`;
  return Array.isArray(schema.type) ? schema.type.join(' or ') : schema.type || 'any JSON value';
}
function constraints(schema) {
  return [
    schema.minimum !== undefined && `min ${schema.minimum}`,
    schema.maximum !== undefined && `max ${schema.maximum}`,
    schema.minLength !== undefined && `min length ${schema.minLength}`,
    schema.maxLength !== undefined && `max length ${schema.maxLength}`,
    schema.minItems !== undefined && `min items ${schema.minItems}`,
    schema.maxItems !== undefined && `max items ${schema.maxItems}`,
    schema.format && `format ${schema.format}`,
    schema.pattern && `pattern ${schema.pattern}`,
    schema.default !== undefined && `default ${JSON.stringify(schema.default)}`,
  ].filter(Boolean).join('; ') || '—';
}

export function renderToolDocs() {
  const sorted = [...tools].sort((a, b) => a.name.localeCompare(b.name, 'en'));
  const lines = [
    '# Tool reference', '',
    '[Documentation home](../../README.md) · [Workflows and pagination](../usage.md) · [Authentication](../authentication.md)', '',
    '<!-- Generated by scripts/generate-tool-docs.mjs. Do not edit directly. -->', '',
    `The registry exposes **${tools.length} tools**; **${tools.filter(tool => tool.outputSchema).length}** declare output schemas. Regenerate with \`npm run docs:generate\`. CI checks this file for drift.`, '',
    'Parameters, defaults, constraints, and descriptions below come from the registry used by MCP discovery. Runtime refinements and GitLab permissions can impose additional constraints. A default makes a parameter optional; “required” describes the input before defaults are applied.', '',
    'Every tool accepts optional `userCredentials` with `accessToken` and optional `gitlabUrl`. A null/empty credential object falls back to transport/environment credentials. Host overrides are ignored with host pinning enabled. See [credential precedence](../authentication.md#credential-precedence); prefer transport secrets over tokens in tool arguments.', '',
    '“Write” uses the registry classification. `execute_custom_query` is dynamic: parsed mutations require write authority. Custom GraphQL/REST tools require user credentials unless shared escape-hatch access is explicitly enabled. Annotations and read classifications are not authorization grants.', '',
    'All results contain JSON text; objects also include structured content. Declared output schemas are shown where present. Additional instance-specific fields may be preserved. See [result contracts](../usage.md#result-contracts-and-errors) for errors, arrays, and null results.', '',
    '## Index', '',
    '| Tool | Access | Declared output schema |', '| --- | --- | --- |',
    ...sorted.map(tool => `| [\`${tool.name}\`](#${tool.name}) | ${tool.name === 'execute_custom_query' ? 'Dynamic' : tool.requiresWrite ? 'Write' : 'Read'} | ${tool.outputSchema ? 'Yes' : 'No'} |`), '',
  ];
  for (const tool of sorted) {
    const schema = schemaOf(tool.inputSchema);
    lines.push(`## ${tool.name}`, '', tool.description, '',
      `Access: **${tool.name === 'execute_custom_query' ? 'Dynamic (query or mutation)' : tool.requiresWrite ? 'Write' : 'Read'}**.`, '',
      '| Parameter | Type / allowed values | Required | Constraints / default | Description |',
      '| --- | --- | --- | --- | --- |');
    const properties = Object.entries(schema.properties || {}).filter(([name]) => name !== 'userCredentials');
    for (const [name, param] of properties) {
      lines.push(`| \`${name}\` | ${cell(typeOf(param))} | ${schema.required?.includes(name) ? 'Yes' : 'No'} | ${cell(constraints(param))} | ${cell(param.description || '—')} |`);
    }
    if (!properties.length) lines.push('| — | — | — | — | No tool-specific parameters |');
    // Preserve exact nested input contracts without bloating the main tables.
    const nested = Object.fromEntries(properties.filter(([, param]) => param.type === 'object' || param.items?.type === 'object'));
    if (Object.keys(nested).length) lines.push('', '<details>', '<summary>Nested parameter schemas</summary>', '', '```json', JSON.stringify(nested, null, 2), '```', '', '</details>');
    if (tool.outputSchema) lines.push('', '<details>', '<summary>Declared output schema</summary>', '', '```json', JSON.stringify(schemaOf(tool.outputSchema), null, 2), '```', '', '</details>');
    lines.push('');
  }
  return lines.join('\n');
}

const target = new URL('../docs/reference/tools.md', import.meta.url);
export function checkToolDocs() {
  if (readFileSync(target, 'utf8') !== renderToolDocs()) throw new Error('Tool reference is stale. Run npm run docs:generate.');
}
if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  if (process.argv.includes('--check')) checkToolDocs();
  else writeFileSync(target, renderToolDocs());
}
